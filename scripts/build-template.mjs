// Builds scope-guard.template.yaml from the agent instruction files and the sample SOW,
// so the template that Switch imports always matches the files in the repo.
// Usage: node scripts/build-template.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8').replace(/\r\n/g, '\n').trimEnd();
const block = (text, indent) => text.split('\n').map((l) => (l ? ' '.repeat(indent) + l : '')).join('\n');

const check = read('agents/check/INSTRUCTIONS.md');
const ledger = read('agents/ledger/INSTRUCTIONS.md');
const sow = read('samples/sow-acme-website.md');
const room = read('agents/ROOM.md');

const yaml = `# Scope Guard: a shared vendor-client room where scope creep becomes priced change orders.
# Generated by scripts/build-template.mjs. Edit the source .md files, not this file.
version: 1
params:
  team:
    type: string
    label: Name prefix
    description: Agents are created as <prefix>-check and <prefix>-ledger.
    default: scope
    pattern: "^[a-z0-9][a-z0-9-]*$"
  client:
    type: user
    label: Client's username
    description: The client's account on the messaging app. They can talk to Scope Check but not the Ledger.
    default: dana
  bridge:
    type: bridge
    default: [Mattermost, $first]
  machine:
    type: machine
    label: Runs on
    default: [$first]
    input: advanced
  check_dir:
    type: directory
    label: Scope Check folder
    default: "{$agents_dir}/scope-check"
    input: advanced
  ledger_dir:
    type: directory
    label: Ledger folder
    default: "{$agents_dir}/scope-ledger"
    input: advanced
agents:
  - name: "{team}-check"
    display_name: Scope Check
    description: Checks every client request against the signed SOW and drafts priced change orders.
    provider: claude
    machine: "{machine}"
    directory: "{check_dir}"
    addressing: anyone
    auto_mode: true
    instructions: |
${block(check, 6)}
  - name: "{team}-ledger"
    display_name: Ledger
    description: Records change orders. Only the vendor can make one billable.
    provider: claude
    machine: "{machine}"
    directory: "{ledger_dir}"
    addressing: owner-agents
    auto_mode: false
    instructions: |
${block(ledger, 6)}
room:
  name: "{team}-acme-website"
  description: Acme Co website project. Vendor and client, with Scope Check and the Ledger.
  bridge: "{bridge}"
  channel_type: channel_private
  agents: ["{team}-check", "{team}-ledger"]
  users: ["{$creator}", "{client}"]
  instructions: |
${block(room, 4)}
  docs:
    - name: SOW
      description: Signed Statement of Work for the Acme Co website. The source of truth for scope.
      instructions: Read this before classifying any request. Cite its section numbers.
      content: |
${block(sow, 8)}
kickoff: "@{team}-check hi! Introduce yourself to the room in 3 short lines and explain how change orders work here."
`;

writeFileSync(join(root, 'scope-guard.template.yaml'), yaml);
console.log('wrote scope-guard.template.yaml', yaml.length, 'bytes');
