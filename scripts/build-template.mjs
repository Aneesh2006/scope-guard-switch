// Builds scope-guard.template.yaml from the agent instruction files, room briefs and sample SOW,
// so the template that Switch imports always matches the files in the repo.
// Usage: node scripts/build-template.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8').replace(/\r\n/g, '\n').trimEnd();
const block = (text, indent) => text.split('\n').map((l) => (l ? ' '.repeat(indent) + l : '')).join('\n');

const watch = read('agents/watch/INSTRUCTIONS.md');
const advisor = read('agents/advisor/INSTRUCTIONS.md');
const clientRoom = read('agents/CLIENT_ROOM.md');
const deskRoom = read('agents/DESK_ROOM.md');
const sow = read('samples/sow-acme-website.md');

const yaml = `# Scope Guard: a silent scope listener in the client channel and a private Scope Desk for the vendor.
# Generated by scripts/build-template.mjs. Edit the source .md files, not this file.
version: 1
params:
  team:
    type: string
    label: Name prefix
    description: Agents are created as <prefix>-watch and <prefix>-advisor.
    default: scope
    pattern: "^[a-z0-9][a-z0-9-]*$"
  bridge:
    type: bridge
    default: [Slack, Mattermost, $first]
  machine:
    type: machine
    label: Runs on
    default: [$first]
    input: advanced
  watch_dir:
    type: directory
    label: Scope Watch folder
    default: "{$agents_dir}/scope-watch"
    input: advanced
  advisor_dir:
    type: directory
    label: Scope Advisor folder
    default: "{$agents_dir}/scope-advisor"
    input: advanced
agents:
  - name: "{team}-watch"
    display_name: Scope Watch
    description: Listens silently to the client channel and alerts the vendor's Scope Desk about out-of-scope requests.
    provider: claude
    machine: "{machine}"
    directory: "{watch_dir}"
    addressing: anyone
    auto_mode: true
    instructions: |
${block(watch, 6)}
  - name: "{team}-advisor"
    display_name: Scope Advisor
    description: The vendor's private assistant. Offers options, drafts client replies and keeps the change-order ledger.
    provider: claude
    machine: "{machine}"
    directory: "{advisor_dir}"
    addressing: owner-agents
    auto_mode: false
    instructions: |
${block(advisor, 6)}
group:
  name: "Acme Co ({team})"
  description: Scope Guard for the Acme Co website project.
rooms:
  - name: "{team}-acme-client"
    description: Project chat with Acme Co. An AI assistant (Scope Watch) reads this channel for the vendor to track scope. It never writes messages here.
    bridge: "{bridge}"
    channel_type: channel_private
    agents: ["{team}-watch"]
    # The client is invited by hand after !assign-agent, so they never see setup commands (README, Setup).
    users: ["{$creator}"]
    instructions: |
${block(clientRoom, 6)}
  - name: "{team}-acme-scope-desk"
    description: The vendor's private Scope Desk. The client is not here.
    bridge: "{bridge}"
    channel_type: channel_private
    agents: ["{team}-watch", "{team}-advisor"]
    users: ["{$creator}"]
    instructions: |
${block(deskRoom, 6)}
    docs:
      - name: SOW
        description: Signed Statement of Work for the Acme Co website. The source of truth for scope.
        instructions: Read this before classifying any request. Cite its section numbers.
        content: |
${block(sow, 10)}
    kickoff: "@{team}-advisor hi! Introduce yourself in 3 short lines, say what the SOW covers, and ask me for meeting notes."
links:
  - { from: "{team}-acme-client", to: "{team}-acme-scope-desk", label: "scope alerts" }
`;

writeFileSync(join(root, 'scope-guard.template.yaml'), yaml);
console.log('wrote scope-guard.template.yaml', yaml.length, 'bytes');
